-- Users are anonymous: a row is an install. `secret` is derived from the
-- token the client keeps, the way the PHP API did it, so tokens issued by
-- that API stay valid after an import.
CREATE TABLE users (
    id      integer GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    secret  text NOT NULL,
    uniqid  text NOT NULL,
    client  text NOT NULL,
    -- Given on the first comment: an adjective and a noun.
    name    text UNIQUE,
    -- The onboarding answers of the app; null when declined or never asked.
    age     text,
    gender  text,
    created timestamptz NOT NULL DEFAULT now()
);

-- A question. The vote counters live in the row: they are bumped as answers
-- arrive, never recounted.
CREATE TABLE items (
    id             integer GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    user_id        integer NOT NULL,
    first_text     text NOT NULL,
    last_text      text NOT NULL,
    status         text NOT NULL DEFAULT 'new' CHECK (status IN ('new', 'approved', 'rejected')),
    reason         text NOT NULL DEFAULT '',
    first_votes    integer NOT NULL DEFAULT 0,
    last_votes     integer NOT NULL DEFAULT 0,
    comments_count integer NOT NULL DEFAULT 0,
    created        timestamptz NOT NULL DEFAULT now()
);
CREATE INDEX items_user ON items (user_id, id);
-- Finds a question asked before, in either order of its answers.
CREATE INDEX items_texts ON items (md5(first_text), md5(last_text));
CREATE INDEX items_new ON items (id) WHERE status = 'new';

-- Everything one user has answered, as three compressed sets of question ids
-- (roaring bitmaps): who picked the first answer, the last one, or skipped.
-- One small row replaces a row per answer, and "what has this user not seen
-- yet" becomes a set difference in memory instead of an anti-join.
CREATE TABLE user_votes (
    user_id integer PRIMARY KEY,
    first   bytea NOT NULL,
    last    bytea NOT NULL,
    skip    bytea NOT NULL
);
-- Bitmaps do not compress; do not spend CPU trying.
ALTER TABLE user_votes
    ALTER COLUMN first SET STORAGE EXTERNAL,
    ALTER COLUMN last SET STORAGE EXTERNAL,
    ALTER COLUMN skip SET STORAGE EXTERNAL;

CREATE TABLE favorites (
    id      integer GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    user_id integer NOT NULL,
    item_id integer NOT NULL,
    UNIQUE (user_id, item_id)
);

CREATE TABLE comments (
    id      integer GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    user_id integer NOT NULL,
    item_id integer NOT NULL,
    parent  integer NOT NULL DEFAULT 0,
    message text NOT NULL,
    abuse   integer NOT NULL DEFAULT 0,
    created timestamptz NOT NULL DEFAULT now()
);
CREATE INDEX comments_item ON comments (item_id, id);
CREATE INDEX comments_user ON comments (user_id, id);

CREATE TABLE reports (
    user_id integer NOT NULL,
    item_id integer NOT NULL,
    reason  text NOT NULL,
    PRIMARY KEY (user_id, item_id, reason)
);
CREATE INDEX reports_item ON reports (item_id);

-- Players moderating new questions: one verdict per user and question.
CREATE TABLE audit (
    item_id integer NOT NULL,
    user_id integer NOT NULL,
    vote    text NOT NULL CHECK (vote IN ('approve', 'decline')),
    PRIMARY KEY (item_id, user_id)
);

-- The vocabulary user names are made of.
CREATE TABLE words (
    word text NOT NULL,
    pos  text NOT NULL CHECK (pos IN ('noun', 'adjv'))
);
